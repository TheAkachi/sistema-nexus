-- Clientes, vínculos com as empresas do guia, assinaturas, configurações, cópia dos planos do site e a fila do plano
-- (contrato 5.2, 5.3, 5.4 e 9.3). Valores em centavos e dias em date, no fuso de São Paulo.

CREATE TABLE clients (
 id text PRIMARY KEY,
 nome text NOT NULL CHECK (length(nome) BETWEEN 2 AND 160),
 responsavel text NOT NULL DEFAULT '',
 whatsapp text NOT NULL DEFAULT '' CHECK (whatsapp ~ '^(55[0-9]{10,11})?$'),
 email text NOT NULL DEFAULT '' CHECK (email = lower(email)),
 notas text NOT NULL DEFAULT '',
 status text NOT NULL DEFAULT 'ativo' CHECK (status IN ('ativo','encerrado')),
 source_key text UNIQUE,
 criado_em timestamptz NOT NULL DEFAULT now(),
 atualizado_em timestamptz NOT NULL DEFAULT now(),
 version integer NOT NULL DEFAULT 1
);

-- A empresa do guia (id do site) tem um cliente só; o cliente pode ter várias (as unidades de uma rede).
CREATE TABLE client_businesses (
 client_id text NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
 business_id text NOT NULL UNIQUE,
 nome_cache text NOT NULL DEFAULT '',
 slug_cache text NOT NULL DEFAULT '',
 bairro_cache text NOT NULL DEFAULT '',
 foto_cache text NOT NULL DEFAULT '',
 vinculado_em timestamptz NOT NULL DEFAULT now(),
 vinculado_por text REFERENCES users(id) ON DELETE SET NULL,
 PRIMARY KEY (client_id, business_id)
);

-- A situação (em dia, a vencer, vencida, inadimplente) é calculada na leitura, nunca guardada (5.3).
CREATE TABLE subscriptions (
 id text PRIMARY KEY,
 client_id text NOT NULL REFERENCES clients(id),
 business_id text,
 plano_site text,
 plano_nome text NOT NULL DEFAULT '',
 valor_centavos integer NOT NULL CHECK (valor_centavos BETWEEN 0 AND 100000000),
 ciclo text NOT NULL CHECK (ciclo IN ('mensal','trimestral','semestral','anual')),
 inicio date NOT NULL,
 vence_em date NOT NULL,
 dia_base integer NOT NULL CHECK (dia_base BETWEEN 1 AND 31),
 status text NOT NULL DEFAULT 'ativa' CHECK (status IN ('ativa','suspensa','cancelada')),
 suspensa_em date,
 cancelada_em date,
 motivo text NOT NULL DEFAULT '',
 origem text NOT NULL CHECK (origem IN ('edirectory','planilha','manual')),
 source_key text UNIQUE,
 notas text NOT NULL DEFAULT '',
 gerida_em timestamptz,
 criado_em timestamptz NOT NULL DEFAULT now(),
 atualizado_em timestamptz NOT NULL DEFAULT now(),
 version integer NOT NULL DEFAULT 1,
 CHECK (vence_em >= inicio),
 CHECK (status <> 'suspensa' OR suspensa_em IS NOT NULL),
 CHECK (status <> 'cancelada' OR cancelada_em IS NOT NULL)
);
CREATE INDEX subscriptions_client ON subscriptions(client_id);
CREATE UNIQUE INDEX subscriptions_uma_por_empresa ON subscriptions(business_id) WHERE status <> 'cancelada' AND business_id IS NOT NULL;

-- Configurações do negócio: uma linha só, já com o padrão provisório (P1 e P2). Nada técnico (D3).
CREATE TABLE settings (
 id integer PRIMARY KEY CHECK (id = 1),
 chave_pix text NOT NULL DEFAULT '',
 modelo_mensagem text NOT NULL,
 tolerancia_dias integer NOT NULL DEFAULT 10 CHECK (tolerancia_dias BETWEEN 0 AND 60),
 atualizado_em timestamptz NOT NULL DEFAULT now(),
 atualizado_por text REFERENCES users(id) ON DELETE SET NULL,
 version integer NOT NULL DEFAULT 1
);
INSERT INTO settings(id,modelo_mensagem) VALUES (1,'Olá, {responsavel}! Aqui é do Nexus. A assinatura do plano {plano} da {empresa} {prazo}, no valor de {valor}. Para renovar, faça o Pix para a chave {chave_pix} e mande o comprovante por aqui. Obrigado!');

-- Cópia dos planos do site, atualizada a cada leitura da integração.
CREATE TABLE site_plans (
 id text PRIMARY KEY,
 nome text NOT NULL,
 pago boolean NOT NULL,
 status text NOT NULL,
 preco_centavos integer CHECK (preco_centavos >= 0),
 atualizado_em timestamptz NOT NULL
);

-- Fila do envio do plano de cada empresa ao site (9.3). O último envio de cada empresa vem pelo seq.
CREATE TABLE plan_sync (
 id text PRIMARY KEY,
 business_id text NOT NULL,
 plano text,
 gerida boolean NOT NULL DEFAULT true,
 subscription_id text REFERENCES subscriptions(id) ON DELETE SET NULL,
 motivo text NOT NULL CHECK (motivo IN ('ativacao','edicao','suspensao','reativacao','cancelamento','desvinculo','pagamento','estorno','tolerancia','importacao','conferencia')),
 criado_em timestamptz NOT NULL DEFAULT now(),
 tentativas integer NOT NULL DEFAULT 0,
 proxima_em timestamptz NOT NULL DEFAULT now(),
 ultimo_erro text NOT NULL DEFAULT '',
 enviado_em timestamptz,
 seq bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX plan_sync_business ON plan_sync(business_id, seq);
CREATE INDEX plan_sync_pendentes ON plan_sync(proxima_em) WHERE enviado_em IS NULL;
